from typing import Any, Protocol


class Backend(Protocol):
    """Provider contract; methods are called under the Endpoint's host lock.

    Regions are (address, byte_length, device_id) rows. prepare also accepts
    (address, byte_length, device_id, stride, count) rows without expansion.
    kind is 'host' or 'cuda'. Providers validate indices, ranges and sizes.
    All handles are provider-private. poll/post return pending/done/error.
    Core calls release_work only after done. Release failures retain ownership.
    Metadata and notification bytes are opaque to Core, not authenticated.
    """

    def register(self, regions: Any, kind: str) -> Any: ...
    def deregister(self, handle: Any) -> None: ...
    def metadata(self) -> bytes: ...
    def connect(self, metadata: bytes) -> str: ...
    def disconnect(self, peer: str) -> None: ...
    def prepare(self, regions: Any, kind: str, peer: str | None) -> Any: ...
    def release_catalog(self, handle: Any) -> None: ...
    def create_work(
        self,
        operation: str,
        local: Any,
        local_indices: Any,
        remote: Any,
        remote_indices: Any,
        notification: bytes,
    ) -> Any: ...
    def post(self, handle: Any) -> str: ...
    def poll(self, handle: Any) -> str: ...
    def release_work(self, handle: Any) -> None: ...
    def notify(self, peer: str, message: bytes) -> None: ...
    def notifications(self) -> dict[str, list[bytes]]: ...
